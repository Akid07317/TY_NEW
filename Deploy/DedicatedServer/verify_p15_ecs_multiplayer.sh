#!/bin/sh
set -eu

usage() {
  cat >&2 <<'EOF'
Usage: Deploy/DedicatedServer/verify_p15_ecs_multiplayer.sh <ssh-user> <host> [ssh-key]

Runs the full P3/P3.5/P4/P5 ECS verification sequence:
1. Public NGO/UTP health check.
2. ECS UDP 7777 ingress check with tcpdump.
3. Public two-client NGO/UTP smoke with spawn/despawn, position sync, attack/HP sync, and P4 death sync.

Set TY_NEW_GAME_PORT, TY_NEW_HEALTH_PORT, TY_NEW_CLIENT1_SECONDS,
TY_NEW_CLIENT2_SECONDS, TY_NEW_CONNECTED_TIMEOUT, TY_NEW_SMOKE_ATTACK_COUNT,
TY_NEW_SMOKE_ATTACK_INTERVAL_SECONDS, TY_NEW_SMOKE_MOVE_DELAY_SECONDS,
TY_NEW_MIN_REMOTE_HEALTH_DROP, TY_NEW_REQUIRE_NETWORK_ENEMY_SYNC,
TY_NEW_REQUIRE_FORMAL_NETWORK_ENEMY_SYNC, TY_NEW_MIN_NETWORK_ENEMY_HEALTH_DROP,
TY_NEW_REQUIRE_NETWORK_ENEMY_ATTACK_SYNC, TY_NEW_MIN_NETWORK_ENEMY_ATTACK_HEALTH_DROP,
TY_NEW_REQUIRE_NETWORK_ENEMY_CHASE_SYNC, TY_NEW_REQUIRE_NETWORK_ENEMY_NAVMESH_CHASE,
TY_NEW_REQUIRE_NETWORK_ENEMY_SERVER_TICK, TY_NEW_MIN_NETWORK_ENEMY_CHASE_DISTANCE,
TY_NEW_MIN_NETWORK_ENEMY_SERVER_TICK_ATTACKS, TY_NEW_REQUIRE_NETWORK_ENEMY_TARGET_SWITCH,
TY_NEW_MIN_NETWORK_ENEMY_INITIAL_TARGET_ATTACKS,
TY_NEW_REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION,
TY_NEW_MIN_NETWORK_ENEMY_TARGET_DISTRIBUTION_TARGETS,
TY_NEW_REQUIRE_NETWORK_ENEMY_TARGET_RETENTION,
TY_NEW_MIN_NETWORK_ENEMY_TARGET_RETENTION_ATTACKS, TY_NEW_MIN_NETWORK_ENEMY_COUNT,
TY_NEW_REQUIRE_DEATH_SYNC, TY_NEW_SKIP_AUTO_FORMAL_SYNC_REQUIREMENTS,
TY_NEW_SKIP_CLIENT_DESPAWN_CHECK, TY_NEW_SKIP_REMOTE_MOVEMENT_CHECK,
TY_NEW_SKIP_HEALTH_SYNC_CHECK,
TY_NEW_USE_BRAIN_CHASE_NETWORK_ENEMY_ATTACK_SMOKE, TY_NEW_ECS_SERVER_LOG,
TY_NEW_ECS_SERVER_TAIL_ERR, or TY_NEW_NETWORK_PLAYER_PREFAB to override defaults.
EOF
  exit 1
}

if [ $# -lt 2 ] || [ $# -gt 3 ]; then
  usage
fi

SSH_USER=$1
HOST=$2
SSH_KEY=${3:-}
PORT=${TY_NEW_GAME_PORT:-7777}
HEALTH_PORT=${TY_NEW_HEALTH_PORT:-7778}
CLIENT1_SECONDS=${TY_NEW_CLIENT1_SECONDS:-35}
CLIENT2_SECONDS=${TY_NEW_CLIENT2_SECONDS:-15}
CONNECTED_TIMEOUT=${TY_NEW_CONNECTED_TIMEOUT:-60}
SMOKE_ATTACK_COUNT=${TY_NEW_SMOKE_ATTACK_COUNT:-4}
SMOKE_ATTACK_INTERVAL_SECONDS=${TY_NEW_SMOKE_ATTACK_INTERVAL_SECONDS:-0.45}
REQUIRE_NETWORK_ENEMY_SYNC=${TY_NEW_REQUIRE_NETWORK_ENEMY_SYNC:-0}
REQUIRE_FORMAL_NETWORK_ENEMY_SYNC=${TY_NEW_REQUIRE_FORMAL_NETWORK_ENEMY_SYNC:-0}
REQUIRE_NETWORK_ENEMY_ATTACK_SYNC=${TY_NEW_REQUIRE_NETWORK_ENEMY_ATTACK_SYNC:-0}
REQUIRE_NETWORK_ENEMY_CHASE_SYNC=${TY_NEW_REQUIRE_NETWORK_ENEMY_CHASE_SYNC:-0}
REQUIRE_NETWORK_ENEMY_NAVMESH_CHASE=${TY_NEW_REQUIRE_NETWORK_ENEMY_NAVMESH_CHASE:-0}
REQUIRE_NETWORK_ENEMY_SERVER_TICK=${TY_NEW_REQUIRE_NETWORK_ENEMY_SERVER_TICK:-0}
REQUIRE_NETWORK_ENEMY_TARGET_SWITCH=${TY_NEW_REQUIRE_NETWORK_ENEMY_TARGET_SWITCH:-0}
REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION=${TY_NEW_REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION:-0}
REQUIRE_NETWORK_ENEMY_TARGET_RETENTION=${TY_NEW_REQUIRE_NETWORK_ENEMY_TARGET_RETENTION:-0}
USE_BRAIN_CHASE_NETWORK_ENEMY_ATTACK_SMOKE=${TY_NEW_USE_BRAIN_CHASE_NETWORK_ENEMY_ATTACK_SMOKE:-0}
if [ "$REQUIRE_NETWORK_ENEMY_TARGET_RETENTION" = "1" ]; then
  REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION=1
fi
if [ "$REQUIRE_NETWORK_ENEMY_TARGET_SWITCH" = "1" ] || [ "$REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION" = "1" ]; then
  REQUIRE_NETWORK_ENEMY_SERVER_TICK=1
fi
if [ "$REQUIRE_NETWORK_ENEMY_SERVER_TICK" = "1" ]; then
  if [ "$REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION" != "1" ]; then
    REQUIRE_NETWORK_ENEMY_SYNC=1
    REQUIRE_NETWORK_ENEMY_ATTACK_SYNC=1
    REQUIRE_NETWORK_ENEMY_CHASE_SYNC=1
  fi
  REQUIRE_NETWORK_ENEMY_NAVMESH_CHASE=1
  USE_BRAIN_CHASE_NETWORK_ENEMY_ATTACK_SMOKE=0
fi
if [ "$REQUIRE_NETWORK_ENEMY_NAVMESH_CHASE" = "1" ]; then
  if [ "$REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION" != "1" ]; then
    REQUIRE_NETWORK_ENEMY_SYNC=1
    REQUIRE_NETWORK_ENEMY_ATTACK_SYNC=1
    REQUIRE_NETWORK_ENEMY_CHASE_SYNC=1
  fi
  if [ "$REQUIRE_NETWORK_ENEMY_SERVER_TICK" != "1" ]; then
    USE_BRAIN_CHASE_NETWORK_ENEMY_ATTACK_SMOKE=1
  fi
fi
if [ "$USE_BRAIN_CHASE_NETWORK_ENEMY_ATTACK_SMOKE" = "1" ]; then
  REQUIRE_NETWORK_ENEMY_CHASE_SYNC=1
fi
if [ "$REQUIRE_NETWORK_ENEMY_SYNC" = "1" ] || [ "$REQUIRE_NETWORK_ENEMY_ATTACK_SYNC" = "1" ] || [ "$REQUIRE_NETWORK_ENEMY_CHASE_SYNC" = "1" ]; then
  SMOKE_MOVE_DELAY_SECONDS=${TY_NEW_SMOKE_MOVE_DELAY_SECONDS:-8}
else
  SMOKE_MOVE_DELAY_SECONDS=${TY_NEW_SMOKE_MOVE_DELAY_SECONDS:-5.5}
fi
MIN_REMOTE_HEALTH_DROP=${TY_NEW_MIN_REMOTE_HEALTH_DROP:-100}
MIN_NETWORK_ENEMY_HEALTH_DROP=${TY_NEW_MIN_NETWORK_ENEMY_HEALTH_DROP:-50}
MIN_NETWORK_ENEMY_ATTACK_HEALTH_DROP=${TY_NEW_MIN_NETWORK_ENEMY_ATTACK_HEALTH_DROP:-25}
MIN_NETWORK_ENEMY_CHASE_DISTANCE=${TY_NEW_MIN_NETWORK_ENEMY_CHASE_DISTANCE:-2.0}
MIN_NETWORK_ENEMY_SERVER_TICK_ATTACKS=${TY_NEW_MIN_NETWORK_ENEMY_SERVER_TICK_ATTACKS:-1}
MIN_NETWORK_ENEMY_INITIAL_TARGET_ATTACKS=${TY_NEW_MIN_NETWORK_ENEMY_INITIAL_TARGET_ATTACKS:-2}
MIN_NETWORK_ENEMY_TARGET_DISTRIBUTION_TARGETS=${TY_NEW_MIN_NETWORK_ENEMY_TARGET_DISTRIBUTION_TARGETS:-2}
MIN_NETWORK_ENEMY_TARGET_RETENTION_ATTACKS=${TY_NEW_MIN_NETWORK_ENEMY_TARGET_RETENTION_ATTACKS:-3}
MIN_NETWORK_ENEMY_COUNT=${TY_NEW_MIN_NETWORK_ENEMY_COUNT:-1}
if [ "$REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION" = "1" ] && [ "$MIN_NETWORK_ENEMY_COUNT" -lt 2 ]; then
  MIN_NETWORK_ENEMY_COUNT=2
fi
if [ "$REQUIRE_NETWORK_ENEMY_TARGET_RETENTION" = "1" ]; then
  MIN_REQUIRED_SERVER_TICK_ATTACKS=$((MIN_NETWORK_ENEMY_COUNT * MIN_NETWORK_ENEMY_TARGET_RETENTION_ATTACKS))
  if [ "$MIN_NETWORK_ENEMY_SERVER_TICK_ATTACKS" -lt "$MIN_REQUIRED_SERVER_TICK_ATTACKS" ]; then
    MIN_NETWORK_ENEMY_SERVER_TICK_ATTACKS=$MIN_REQUIRED_SERVER_TICK_ATTACKS
  fi
fi
NETWORK_PLAYER_PREFAB=${TY_NEW_NETWORK_PLAYER_PREFAB:-}
REQUIRE_DEATH_SYNC=${TY_NEW_REQUIRE_DEATH_SYNC:-1}
SKIP_AUTO_FORMAL_SYNC_REQUIREMENTS=${TY_NEW_SKIP_AUTO_FORMAL_SYNC_REQUIREMENTS:-0}
SKIP_CLIENT_DESPAWN_CHECK=${TY_NEW_SKIP_CLIENT_DESPAWN_CHECK:-0}
SKIP_REMOTE_MOVEMENT_CHECK=${TY_NEW_SKIP_REMOTE_MOVEMENT_CHECK:-0}
SKIP_HEALTH_SYNC_CHECK=${TY_NEW_SKIP_HEALTH_SYNC_CHECK:-0}
PROJECT_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
PREFAB_ARGS=""
FORMAL_SYNC_ARGS=""
DEATH_SYNC_ARGS=""
SMOKE_SKIP_ARGS=""
NETWORK_ENEMY_ARGS=""
REMOTE="$SSH_USER@$HOST"
SERVER_LOG=${TY_NEW_ECS_SERVER_LOG:-/tmp/TY_NEW_p3_ecs_public_server_placeholder.log}
SERVER_TAIL_ERR=${TY_NEW_ECS_SERVER_TAIL_ERR:-/tmp/TY_NEW_p610_ecs_server_tail.err}
REMOTE_SERVER_LOG_TAIL_PID=""

if [ -n "$NETWORK_PLAYER_PREFAB" ]; then
  PREFAB_ARGS="--network-player-prefab $NETWORK_PLAYER_PREFAB"
fi

if [ "$SKIP_AUTO_FORMAL_SYNC_REQUIREMENTS" = "1" ]; then
  FORMAL_SYNC_ARGS="--skip-auto-formal-sync-requirements"
fi

if [ "$REQUIRE_DEATH_SYNC" = "1" ]; then
  DEATH_SYNC_ARGS="--require-death-sync"
fi

if [ "$SKIP_CLIENT_DESPAWN_CHECK" = "1" ]; then
  SMOKE_SKIP_ARGS="$SMOKE_SKIP_ARGS --skip-client-despawn-check"
fi

if [ "$SKIP_REMOTE_MOVEMENT_CHECK" = "1" ]; then
  SMOKE_SKIP_ARGS="$SMOKE_SKIP_ARGS --skip-remote-movement-check"
fi

if [ "$SKIP_HEALTH_SYNC_CHECK" = "1" ]; then
  SMOKE_SKIP_ARGS="$SMOKE_SKIP_ARGS --skip-health-sync-check"
fi

if [ "$REQUIRE_NETWORK_ENEMY_SYNC" = "1" ]; then
  NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --require-network-enemy-sync --min-network-enemy-health-drop $MIN_NETWORK_ENEMY_HEALTH_DROP"
  if [ "$REQUIRE_FORMAL_NETWORK_ENEMY_SYNC" = "1" ]; then
    NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --require-formal-network-enemy-sync"
  fi
fi
if [ "$REQUIRE_NETWORK_ENEMY_ATTACK_SYNC" = "1" ]; then
  NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --require-network-enemy-attack-sync --min-network-enemy-attack-health-drop $MIN_NETWORK_ENEMY_ATTACK_HEALTH_DROP"
fi
if [ "$REQUIRE_NETWORK_ENEMY_CHASE_SYNC" = "1" ]; then
  NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --require-network-enemy-chase-sync --min-network-enemy-chase-distance $MIN_NETWORK_ENEMY_CHASE_DISTANCE"
fi
if [ "$REQUIRE_NETWORK_ENEMY_NAVMESH_CHASE" = "1" ]; then
  if [ "$REQUIRE_NETWORK_ENEMY_TARGET_RETENTION" = "1" ]; then
    SERVER_LOG=${TY_NEW_ECS_SERVER_LOG:-/tmp/TY_NEW_p620_ecs_server_live.log}
  elif [ "$REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION" = "1" ]; then
    SERVER_LOG=${TY_NEW_ECS_SERVER_LOG:-/tmp/TY_NEW_p618_ecs_server_live.log}
  elif [ "$REQUIRE_NETWORK_ENEMY_TARGET_SWITCH" = "1" ]; then
    SERVER_LOG=${TY_NEW_ECS_SERVER_LOG:-/tmp/TY_NEW_p615_ecs_server_live.log}
  else
    SERVER_LOG=${TY_NEW_ECS_SERVER_LOG:-/tmp/TY_NEW_p614_ecs_server_live.log}
  fi
  NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --require-network-enemy-navmesh-chase"
fi
if [ "$REQUIRE_NETWORK_ENEMY_SERVER_TICK" = "1" ]; then
  NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --require-network-enemy-server-tick --min-network-enemy-server-tick-attacks $MIN_NETWORK_ENEMY_SERVER_TICK_ATTACKS"
fi
if [ "$REQUIRE_NETWORK_ENEMY_TARGET_SWITCH" = "1" ]; then
  NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --require-network-enemy-target-switch --min-network-enemy-initial-target-attacks $MIN_NETWORK_ENEMY_INITIAL_TARGET_ATTACKS"
fi
if [ "$REQUIRE_NETWORK_ENEMY_TARGET_DISTRIBUTION" = "1" ]; then
  NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --require-network-enemy-target-distribution --min-network-enemy-target-distribution-targets $MIN_NETWORK_ENEMY_TARGET_DISTRIBUTION_TARGETS"
fi
if [ "$REQUIRE_NETWORK_ENEMY_TARGET_RETENTION" = "1" ]; then
  NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --require-network-enemy-target-retention --min-network-enemy-target-retention-attacks $MIN_NETWORK_ENEMY_TARGET_RETENTION_ATTACKS"
fi
if [ "$USE_BRAIN_CHASE_NETWORK_ENEMY_ATTACK_SMOKE" = "1" ]; then
  NETWORK_ENEMY_ARGS="$NETWORK_ENEMY_ARGS --use-brain-chase-network-enemy-attack-smoke"
fi

stop_remote_server_log_tail() {
  if [ -n "$REMOTE_SERVER_LOG_TAIL_PID" ]; then
    kill "$REMOTE_SERVER_LOG_TAIL_PID" 2>/dev/null || true
    wait "$REMOTE_SERVER_LOG_TAIL_PID" 2>/dev/null || true
    REMOTE_SERVER_LOG_TAIL_PID=""
  fi
}

start_remote_server_log_tail() {
  if [ "$REQUIRE_NETWORK_ENEMY_NAVMESH_CHASE" != "1" ]; then
    return
  fi

  : > "$SERVER_LOG"
  : > "$SERVER_TAIL_ERR"
  echo "Tailing remote server log from $REMOTE:/var/log/ty-new/server.log into $SERVER_LOG"
  if [ -n "$SSH_KEY" ]; then
    ssh -i "$SSH_KEY" "$REMOTE" "sudo tail -n 0 -F /var/log/ty-new/server.log" > "$SERVER_LOG" 2> "$SERVER_TAIL_ERR" &
  else
    ssh "$REMOTE" "sudo tail -n 0 -F /var/log/ty-new/server.log" > "$SERVER_LOG" 2> "$SERVER_TAIL_ERR" &
  fi
  REMOTE_SERVER_LOG_TAIL_PID=$!
  sleep 1

  if ! kill -0 "$REMOTE_SERVER_LOG_TAIL_PID" 2>/dev/null; then
    echo "Remote server log tail failed before the smoke started." >&2
    tail -n 20 "$SERVER_TAIL_ERR" >&2 || true
    exit 1
  fi
}

trap stop_remote_server_log_tail EXIT INT TERM

echo "Checking public NGO/UTP health on $HOST:$HEALTH_PORT"
"$PROJECT_ROOT/Deploy/DedicatedServer/probe_p15_multiplayer.py" \
  --health-only \
  --host "$HOST" \
  --game-port "$PORT" \
  --health-port "$HEALTH_PORT" \
  --startup-timeout 5 \
  --socket-timeout 5

echo "Checking public UDP ingress on $HOST:$PORT"
if [ -n "$SSH_KEY" ]; then
  TY_NEW_UDP_PORT="$PORT" "$PROJECT_ROOT/Deploy/DedicatedServer/probe_udp_ingress.sh" "$SSH_USER" "$HOST" "$SSH_KEY"
else
  TY_NEW_UDP_PORT="$PORT" "$PROJECT_ROOT/Deploy/DedicatedServer/probe_udp_ingress.sh" "$SSH_USER" "$HOST"
fi

echo "Running public two-client multiplayer smoke"
start_remote_server_log_tail
"$PROJECT_ROOT/Deploy/DedicatedServer/probe_p15_multiplayer.py" \
  --skip-server-start \
  --host "$HOST" \
  --game-port "$PORT" \
  --health-port "$HEALTH_PORT" \
  --connected-timeout "$CONNECTED_TIMEOUT" \
  --disconnect-timeout 30 \
  --server-log "$SERVER_LOG" \
  --client1-log /tmp/TY_NEW_p3_ecs_public_client1.log \
  --client2-log /tmp/TY_NEW_p3_ecs_public_client2.log \
  --client1-quit-after-seconds "$CLIENT1_SECONDS" \
  --client2-quit-after-seconds "$CLIENT2_SECONDS" \
  --min-remote-move-distance 0.25 \
  --smoke-move-delay-seconds "$SMOKE_MOVE_DELAY_SECONDS" \
  --smoke-attack-count "$SMOKE_ATTACK_COUNT" \
  --smoke-attack-interval-seconds "$SMOKE_ATTACK_INTERVAL_SECONDS" \
  --min-remote-health-drop "$MIN_REMOTE_HEALTH_DROP" \
  $NETWORK_ENEMY_ARGS \
  $PREFAB_ARGS \
  $FORMAL_SYNC_ARGS \
  $SMOKE_SKIP_ARGS \
  --min-network-enemy-count "$MIN_NETWORK_ENEMY_COUNT" \
  $DEATH_SYNC_ARGS
